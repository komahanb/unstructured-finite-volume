!=====================================================================!
! Module that states restarted GMRES on the tower.
!
! For any operator, symmetric or not: build an orthonormal basis of
! the Krylov directions generated by the operator, and take the
! minimising solution that basis can express,
!
!      minimise || rhs - A x ||   over   x0 + span{r, Ar, A^2 r, ...}
!
! The basis grows one matvec at a time (Arnoldi, with the inner
! product keeping it orthonormal); a pair of rotations keeps the small
! problem triangular, so that the residual norm is read without
! solving the small problem until the end. After `restart` directions
! the basis is discarded and the iteration restarts from the current
! iterate:
!
!   A M^-1 v_j = h(1, j) v_1 + ... + h(j + 1, j) v_(j+1)      Arnoldi
!
!   h after the rotations         s, the rotated |r| e_1
!   [ x  x  x  x ]                [ s1 ]
!   [    x  x  x ]                [ s2 ]
!   [       x  x ]                [ s3 ]
!   [          x ]                [ s4 ]
!   [            ]                [ s5 ]   |s(j + 1)|, the residual of
!                                          the candidate
!
! Everything the solver needs is inherited: matvec, inner_product,
! norm. This module states the iteration and nothing more.
!
! A preconditioner, when stored, is a minimizer stated on the same
! operator and applied on the right: each basis direction is
! preconditioned before the operator acts on it, so the basis spans
! the Krylov directions of A M^-1, the quantity minimised is the
! residual of the equations themselves, and the candidate is
! x + M^-1 (the combination of the basis). A preconditioner applied on
! the left minimises M^-1 r instead, whose reduction the restarts
! cannot read as the residual's own.
!
! Author: Komahan Boopathy (komahan@gatech.edu)
!=====================================================================!

module operation_gmres

  use iso_fortran_env    , only : int64
  use util_verbosity     , only : verbosity
  use util_precision     , only : dp
  use operation_minimizer, only : minimizer, state, restrict, solve_result, SOLVE_BREAKDOWN, SOLVE_INNER_FAILED, SOLVE_STAGNATED
  use operation_minimizer, only : saturated_sum
  use, intrinsic :: ieee_arithmetic, only : ieee_is_finite
  use util_tally         , only : linear_solves, tally
  use view_directed      , only : directed_graph
  use operation_exchange , only : blocked
  use graph_fractal      , only : graph
  use operation_action   , only : operation
  use field_stored       , only : stored_field

  implicit none

  private

  public :: gmres

  !-------------------------------------------------------------------!
  ! Type that models restarted GMRES, a member of the minimizer
  ! hierarchy, with its restart length and its preconditioner
  !-------------------------------------------------------------------!

  type, extends(minimizer) :: gmres

     integer                       :: restart = 30
     class(minimizer), allocatable :: preconditioner

   contains

     procedure :: name            => gmres_name
     procedure :: state           => gmres_state
     procedure :: restrict        => gmres_restrict
     procedure :: bind_account    => gmres_bind_account
     procedure :: storage_entries => gmres_storage_entries
     procedure :: solve

  end type gmres

  ! A GMRES stated by its preconditioner and its options
  interface gmres
     module procedure gmres_of
  end interface gmres

contains

  !===================================================================!
  ! Returns the name of the iteration
  !===================================================================!

  pure function gmres_name(this) result(name)

    class(gmres)    , intent(in)  :: this
    character(len=:), allocatable :: name

    ! Names this, which the name does not read, to keep the compiler
    ! from warning that the argument is unused
    associate (u1 => this); end associate

    name = 'gmres'

  end function gmres_name

  !===================================================================!
  ! States the operator on this solver and on its preconditioner. A
  ! blocked preconditioner is stated with the coupling of the blocks,
  ! the unknowns' coupling read through them, and shares the
  ! distribution over the images with its halo.
  !===================================================================!

  subroutine gmres_state(this, action, context, unknown_domain, num_unknowns, &
       & num_components, coupling, stored_inputs)

    class(gmres)         , intent(inout)        :: this
    class(operation)     , intent(in)           :: action
    class(directed_graph), intent(in)           :: context
    type(graph)          , intent(in)           :: unknown_domain
    integer              , intent(in)           :: num_unknowns
    integer              , intent(in), optional :: num_components
    class(directed_graph), intent(in), optional :: coupling
    type(stored_field)   , intent(in), optional :: stored_inputs(:)

    call state(this, action, context, unknown_domain, num_unknowns, &
         & num_components, coupling, stored_inputs)
    if (allocated(this % preconditioner)) then
       if (allocated(this % distribution)) this % preconditioner % distribution = this % distribution
       if (this % preconditioner % block_width > 1) then
          if (present(coupling)) then
             call this % preconditioner % state(action, context, unknown_domain, num_unknowns, &
                  & num_components, blocked(coupling, this % preconditioner % block_width), stored_inputs)
          else
             call this % preconditioner % state(action, context, unknown_domain, num_unknowns, &
                  & num_components, blocked(context, this % preconditioner % block_width), stored_inputs)
          end if
       else
          call this % preconditioner % state(action, context, unknown_domain, num_unknowns, &
               & num_components, coupling, stored_inputs)
       end if
    end if

  end subroutine gmres_state

  !===================================================================!
  ! Restricts the solve to the selected unknowns. The preconditioner
  ! is stated on the same operator, so it is restricted by the
  ! selection itself.
  !===================================================================!

  subroutine gmres_restrict(this, selected)

    class(gmres), intent(inout) :: this
    integer     , intent(in)    :: selected(:)

    call restrict(this, selected)
    if (allocated(this % preconditioner)) call this % preconditioner % restrict(selected)

  end subroutine gmres_restrict

  !===================================================================!
  ! Returns the entries stored: the Krylov basis of restart + 1
  ! vectors over the unknowns, and whatever the preconditioner retains
  !===================================================================!

  pure integer(int64) function gmres_storage_entries(this, num_unknowns) result(entries)

    class(gmres), intent(in) :: this
    integer     , intent(in) :: num_unknowns

    integer :: m

    m = min(max(this % restart, 1), max(num_unknowns, 1))
    entries = int(m + 1, int64) * int(num_unknowns, int64)
    if (allocated(this % preconditioner)) then
       entries = saturated_sum(entries, this % preconditioner % storage_entries(num_unknowns))
    end if

  end function gmres_storage_entries

  !===================================================================!
  ! Returns the direction through the preconditioner, M^-1 v, or v
  ! itself when none is stored, and whether it is admissible: finite,
  ! and from a preconditioner solve that did not fail
  !===================================================================!

  subroutine preconditioned(this, v, z, direction_admissible)

    class(gmres)         , intent(inout) :: this
    real(dp)             , intent(in)    :: v(:)
    real(dp), allocatable, intent(out)   :: z(:)
    logical              , intent(out)   :: direction_admissible

    real(dp)           :: reduced
    type(solve_result) :: outcome

    direction_admissible = .true.
    if (.not. allocated(this % preconditioner)) then
       z = v
       direction_admissible = all(ieee_is_finite(z))
       return
    end if
    allocate(z(size(v)), source=0.0_dp)
    call this % preconditioner % solve(v, z, reduced)
    outcome = this % preconditioner % result()
    direction_admissible = .not. outcome % failed() .and. ieee_is_finite(reduced) .and. all(ieee_is_finite(z))

  end subroutine preconditioned

  !===================================================================!
  ! Solves A x = rhs by restarted cycles, and returns the norm of the
  ! residual achieved:
  !
  !   a cycle:   r = rhs - A x, beta = |r|, v_1 = r / beta
  !              j = 1 .. restart: a direction, orthonormalised, the
  !                  rotations applied, |s(j + 1)| read
  !              y from the triangle, x = x + M^-1 (V y), r measured
  !   then:      converged, broken down or invariant: return;
  !              otherwise the next cycle
  !===================================================================!

  subroutine solve(this, rhs, x, achieved)

    class(gmres), intent(inout) :: this
    real(dp)    , intent(in)    :: rhs(:)
    real(dp)    , intent(inout) :: x(:)
    real(dp)    , intent(out)   :: achieved

    real(dp), allocatable :: basis(:,:), h(:,:), cs(:), sn(:), s(:)
    real(dp), allocatable :: r(:), w(:), y(:), z(:)
    real(dp)              :: beta, hik, radius, subdiag, unpreconditioned, first_residual
    integer               :: n, m, outer, i, j, k
    logical               :: direction_admissible, breakdown, invariant

    call this % record_event(linear_solves)

    n = size(x)
    m = min(max(this % restart, 1), n)

    allocate(basis(n, m + 1), h(m + 1, m), cs(m), sn(m), s(m + 1))

    call this % initialize_residual_history()
    call this % imbalance(rhs, x, r)
    achieved = this % norm(r)
    first_residual = achieved
    if (this % terminated(achieved, 0)) return

    do outer = 1, this % max_iterations

       ! The preconditioning is on the right: the basis spans the
       ! Krylov space of A M^-1 from the residual itself, so the
       ! minimised quantity |s(j+1)| is the residual of the equations,
       ! and the candidate is x + M^-1 (sum of y_i basis_i).
       unpreconditioned = achieved
       beta = achieved
       if (.not. ieee_is_finite(beta)) then
          call this % record_result(achieved, outer - 1, SOLVE_INNER_FAILED)
          return
       end if
       if (beta <= tiny(1.0_dp)) then
          call this % record_result(achieved, outer - 1, SOLVE_BREAKDOWN)
          return
       end if
       basis = 0.0_dp
       h  = 0.0_dp
       s  = 0.0_dp
       s(1) = beta
       basis(:, 1) = r / beta
       breakdown = .false.
       invariant = .false.
       k = 0

       do j = 1, m

          ! One more direction from the operator, orthonormalised. The
          ! unrotated subdiagonal is retained separately: the rotations
          ! overwrite its entry, and both the next basis vector and the
          ! breakdown test need the unrotated value.
          call preconditioned(this, basis(:, j), z, direction_admissible)
          if (.not. direction_admissible) then
             call this % record_result(unpreconditioned, outer - 1, SOLVE_INNER_FAILED)
             achieved = unpreconditioned
             return
          end if
          call this % matvec(z, w)
          ! Over the images, the orthogonalisation runs on the owned
          ! entries; every other entry of w is zero and stays so
          do i = 1, j
             h(i, j) = this % inner_product(w, basis(:, i))
             if (allocated(this % distribution)) then
                associate (own => this % distribution % owned)
                  w(own) = w(own) - h(i, j) * basis(own, i)
                end associate
             else
                w = w - h(i, j) * basis(:, i)
             end if
          end do
          subdiag     = this % norm(w)
          h(j + 1, j) = subdiag
          invariant = subdiag <= tiny(1.0_dp) .or. j == n

          if (j < m .and. subdiag > tiny(1.0_dp)) then
             basis(:, j + 1) = w / subdiag
          end if

          ! The previous rotations, then the new one
          do i = 1, j - 1
             hik        = cs(i) * h(i, j) + sn(i) * h(i + 1, j)
             h(i + 1, j) = -sn(i) * h(i, j) + cs(i) * h(i + 1, j)
             h(i, j)     = hik
          end do

          radius = hypot(h(j, j), h(j + 1, j))
          if (radius <= tiny(1.0_dp)) then
             k = j - 1
             breakdown = .true.
             exit
          end if
          cs(j) = h(j, j) / radius
          sn(j) = h(j + 1, j) / radius
          h(j, j)     = radius
          h(j + 1, j) = 0.0_dp

          s(j + 1) = -sn(j) * s(j)
          s(j)     =  cs(j) * s(j)

          k = j
          ! The residual of the candidate this basis expresses; its
          ! acceptance below measures rhs - A x directly
          achieved = abs(s(j + 1))
          if (this % converged(achieved)) exit
          if (subdiag <= tiny(1.0_dp)) exit

       end do

       ! The minimising solution this basis can express: y from the
       ! triangle by back substitution, then x + M^-1 (V y)
       allocate(y(k))
       do i = k, 1, -1
          y(i) = s(i)
          do j = i + 1, k
             y(i) = y(i) - h(i, j) * y(j)
          end do
          y(i) = y(i) / h(i, i)
       end do
       z = 0.0_dp
       do i = 1, k
          if (allocated(this % distribution)) then
             associate (own => this % distribution % owned)
               z(own) = z(own) + y(i) * basis(own, i)
             end associate
          else
             z = z + y(i) * basis(:, i)
          end if
       end do
       deallocate(y)
       call preconditioned(this, z, w, direction_admissible)
       if (.not. direction_admissible) then
          call this % record_result(unpreconditioned, outer - 1, SOLVE_INNER_FAILED)
          achieved = unpreconditioned
          return
       end if
       x = x + w

       call this % imbalance(rhs, x, r)
       achieved = this % norm(r)
       ! One line per restart cycle at verbosity two
       if (verbosity >= 2) then
          print '(a,i4,a,i3,a,es12.4,a,es12.4)', '        gmres cycle ', outer, '  directions ', k, &
               & '  |r| = ', achieved, '  |r|/|r0| = ', achieved / max(first_residual, tiny(1.0_dp))
       end if
       if (breakdown .and. .not. this % converged(achieved)) then
          call this % record_residual_norm(achieved)
          call this % record_result(achieved, outer, SOLVE_BREAKDOWN)
          return
       end if
       if (this % terminated(achieved, outer)) return
       ! An invariant Krylov space has no further direction to add. A
       ! discrepancy in its true residual (for example, a numerical
       ! directional difference) is reported as stagnation, not as a
       ! converged solve. An outer minimizer may use the finite step.
       if (invariant) then
          call this % record_result(achieved, outer, SOLVE_STAGNATED)
          return
       end if

    end do

  end subroutine solve

  !===================================================================!
  ! Binds the account of this minimizer and of its children
  !===================================================================!

  subroutine gmres_bind_account(this, account)

    class(gmres)        , intent(inout) :: this
    type(tally), pointer, intent(in)    :: account

    this % account => account
    if (allocated(this % preconditioner)) call this % preconditioner % bind_account(account)

  end subroutine gmres_bind_account

  !===================================================================!
  ! Creates a GMRES preconditioned by a minimizer, restarted every
  ! restart directions, to the tolerance relative to its first residual
  !===================================================================!

  function gmres_of(preconditioner, restart, tolerance) result(this)
    class(minimizer), intent(in), optional :: preconditioner
    integer         , intent(in), optional :: restart
    real(dp)        , intent(in), optional :: tolerance
    type(gmres)                            :: this
    if (present(preconditioner)) allocate(this % preconditioner, source=preconditioner)
    if (present(restart))   this % restart   = restart
    if (present(tolerance)) this % tolerance = tolerance
  end function gmres_of

end module operation_gmres
